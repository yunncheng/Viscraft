export const LINE_H = 10;
export const COVERAGE = Object.keys(G).join('');
export const glyphW = ch => (G[ch] || G['?'])[0].length;
export const hasGlyph = ch => G[ch] !== undefined;
export function textW(s, sc = 1) {
  let w = 0;
  for (const ch of s) w += (glyphW(ch) + 1) * sc;
  return Math.max(0, w - sc);
}

/** Draw a string; `col` is a palette index or a (row, column) => index fn. */
export function text(fb, s, x0, y0, col, shadow = null, sc = 1) {
  let x = x0;
  for (const ch of s) {
    const g = G[ch] || G['?'];
    for (let y = 0; y < g.length; y++)
      for (let b = 0; b < g[y].length; b++)
        if (g[y][b] === '#') {
          if (shadow !== null) fb.rect(x + b * sc + 1, y0 + y * sc + 1, sc, sc, shadow);
        }
    for (let y = 0; y < g.length; y++)
      for (let b = 0; b < g[y].length; b++)
        if (g[y][b] === '#') fb.rect(x + b * sc, y0 + y * sc, sc, sc, typeof col === 'function' ? col(y, b) : col);
    x += (g[0].length + 1) * sc;
  }
  return x;
}
