test('endpoint: locality is a per-deployment authorization rule, not the adapter identity', async () => {
  await withRoot(async root => {
    // Remote plain HTTP is refused (requires HTTPS) before any record.
    await assert.rejects(
      () =>
        generateImageApi(root, source(60), 'build/x.png', {
          endpoint: { protocol: 'vllm-omni-image', baseUrl: 'http://images.example.com' },
          authorization: { submit: true },
        }),
      /loopback|https/i,
    );
    // Remote HTTPS without the explicit submit authorization is refused (no request).
    await assert.rejects(
      () =>
        generateImageApi(root, source(61), 'build/x.png', {
          endpoint: { protocol: 'vllm-omni-image', baseUrl: 'https://images.example.com' },
        }),
      /authorization/i,
    );
    // A credential-carrying or shaped URL is refused.
    await assert.rejects(
      () =>
        generateImageApi(root, source(62), 'build/x.png', {
          endpoint: { protocol: 'vllm-omni-image', baseUrl: 'https://user:pass@images.example.com' },
          authorization: { submit: true },
        }),
      /credential/i,
    );
    assert.ok(!existsSync(join(root, '.viscraft', 'jobs', 'image-api')), 'a refused endpoint must not create a job');
  });
});

test('generate: a successful loopback run decodes genuine PNG bytes and records matching provenance', async () => {
  await withRoot(async root => {
    await withFixture(async fixture => {
      const src = source(1, { size: '512x512', seed: 123 });
      const result = await generateImageApi(root, src, 'build/out.png', {
        testOnly: { baseUrl: fixture.baseUrl },
      });

      assert.equal(result.backend, 'vllm-omni-image/Qwen-Image');
      assert.equal(result.generation.provider, 'vllm-omni-image');
      assert.equal(result.generation.model, 'Qwen-Image');
      assert.equal(result.generation.operation, 'generate');
      assert.equal(result.generation.simulated, true, 'a test-only run is simulated');
      assert.deepEqual(result.generation.inputSha256, []);
      assert.deepEqual(result.generation.references, []);
      assert.equal(result.generation.size, '512x512');
      assert.equal(result.generation.seed, 123);
      assert.deepEqual(Object.keys(result.generation).sort(), [
        'extensionHash',
        'inputSha256',
        'model',
        'operation',
        'outputSha256',
        'promptHash',
        'provider',
        'references',
        'requestHash',
        'seed',
        'simulated',
        'size',
      ]);

      const bytes = await readFile(join(root, 'build', 'out.png'));
      assert.deepEqual(
        [...bytes.subarray(0, 8)],
        [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a],
        'output must be a genuine PNG',
      );
      assert.equal(createHash('sha256').update(bytes).digest('hex'), result.generation.outputSha256);
      assert.equal(
        result.generation.outputSha256,
        createHash('sha256')
          .update(await providerPng())
          .digest('hex'),
      );

      const retained = join(root, PROVIDER_FILE_REL(1));
      assert.ok(existsSync(retained), 'original provider image must be retained');
      assert.equal(await hashFile(retained), result.generation.outputSha256);

      assert.equal(fixture.state.requests.length, 1);
      assert.equal(fixture.state.requests[0].path, '/v1/images/generations');
      const body = JSON.parse(fixture.state.requests[0].body.toString('utf8')) as Record<string, unknown>;
      assert.equal(body.prompt, src.prompt);
      assert.equal(body.model, 'Qwen-Image');
      assert.equal(body.size, '512x512');
      assert.equal(body.seed, 123);
      assert.equal(body.response_format, 'b64_json');

      const job = await readJob(root, 1);
      assert.equal(job.schemaVersion, 1);
      assert.equal(job.state, 'succeeded');
      assert.equal(job.submitted, 1);
      assert.equal(job.endpoint, 'test');
      assert.equal(job.outputSha256, result.generation.outputSha256);
      assert.equal(job.outputPath, PROVIDER_FILE_REL(1));

      // Re-materializing a succeeded attempt must not touch the network.
      const restored = await generateImageApi(root, src, 'exports/again.png', {
        testOnly: { baseUrl: fixture.baseUrl },
      });
      assert.equal(restored.generation.outputSha256, result.generation.outputSha256);
      assert.ok(existsSync(join(root, 'exports', 'again.png')));
      assert.equal(fixture.state.requests.length, 1, 'a succeeded attempt must never resubmit');
      const unsupported = JSON.stringify({ ...job, schemaVersion: 99 });
      await writeFile(join(root, JOB_FILE_REL(1)), unsupported);
      await assert.rejects(
        () => generateImageApi(root, src, 'exports/unsupported.png', { testOnly: { baseUrl: fixture.baseUrl } }),
        /job record failed validation/,
      );
      assert.equal(
        await readFile(join(root, JOB_FILE_REL(1)), 'utf8'),
        unsupported,
        'unsupported state must remain intact without conversion',
      );
      assert.equal(fixture.state.requests.length, 1, 'unreadable state must never trigger another submission');
    });
  });
});

test('edit: a loopback run transmits the reference Asset only with explicit per-Asset consent', async () => {
  await withRoot(async root => {
    await withFixture(async fixture => {
      const ref = await hero(root);
      const src = source(2, {
        operation: 'edit',
        references: [{ asset: 'hero', category: 'image', role: 'identity' }],
      });
      const endpoint = { protocol: 'vllm-omni-image' as const, baseUrl: fixture.baseUrl };

      // Authorized submit, but the reference Asset is not in uploadAssets.
      await assert.rejects(
        () =>
          generateImageApi(root, src, 'build/edit.png', {
            endpoint,
            authorization: { submit: true },
            references: [ref],
          }),
        /upload|consent|authorization/i,
      );
      assert.equal(fixture.state.requests.length, 0, 'no request may be sent without upload consent');
      assert.ok(!existsSync(join(root, JOB_FILE_REL(2))), 'no job record may be written without upload consent');

      const result = await generateImageApi(root, src, 'build/edit.png', {
        endpoint,
        authorization: { submit: true, uploadAssets: ['hero'] },
        references: [ref],
      });
      assert.equal(result.generation.operation, 'edit');
      assert.deepEqual(result.generation.inputSha256, [ref.asset.sha256]);
      assert.equal(result.generation.simulated, false, 'an authorized non-test run is not simulated');
      assert.equal(fixture.state.requests.length, 1);
      assert.equal(fixture.state.requests[0].path, '/v1/images/edits');
      const multipart = fixture.state.requests[0].body.toString('utf8');
      assert.match(multipart, /name="prompt"/);
      assert.match(multipart, /name="image"; filename="reference\.png"/);
      assert.match(multipart, /name="response_format"/);
    });
  });
});

test('credential: the env var named by the endpoint is resolved at call time and never persisted', async () => {
  await withRoot(async root => {
    await withFixture(async fixture => {
      const endpoint = { protocol: 'vllm-omni-image' as const, baseUrl: fixture.baseUrl, credential: CREDENTIAL_ENV };
      process.env[CREDENTIAL_ENV] = 'sk-live-TEST0123456789';
      try {
        const result = await generateImageApi(root, source(50), 'build/cred.png', {
          endpoint,
          authorization: { submit: true },
        });
        assert.equal(result.generation.simulated, false);
        assert.equal(fixture.state.requests.length, 1);
        assert.equal(fixture.state.requests[0].headers.authorization, `Bearer sk-live-TEST0123456789`);
        const jobRaw = await readFile(join(root, JOB_FILE_REL(50)), 'utf8');
        assert.ok(!jobRaw.includes('sk-live-TEST0123456789'), 'the credential must never be persisted');
        assert.ok(
          !JSON.stringify(result.generation).includes('sk-live-TEST0123456789'),
          'the credential must never reach the generation record',
        );
      } finally {
        delete process.env[CREDENTIAL_ENV];
      }

      // A missing credential is a loud error and sends nothing.
      await assert.rejects(
        () => generateImageApi(root, source(51), 'build/cred2.png', { endpoint, authorization: { submit: true } }),
        /credential/i,
      );
      assert.ok(!existsSync(join(root, JOB_FILE_REL(51))), 'a missing credential must not create a job');

      // A non-printable credential is also a loud error.
      process.env[CREDENTIAL_ENV] = 'bad key with space';
      try {
        await assert.rejects(
          () =>
            generateImageApi(root, source(52), 'build/cred3.png', {
              endpoint,
              authorization: { submit: true },
            }),
          /credential/i,
        );
      } finally {
        delete process.env[CREDENTIAL_ENV];
      }
      assert.equal(fixture.state.requests.length, 1, 'no request may be sent without a usable credential');
    });
  });
});

test('an ambiguous submit is never resubmitted', async () => {
  const modes: FixtureMode[] = ['http500', 'network', 'malformed'];
  for (let index = 0; index < modes.length; index++) {
    const mode = modes[index];
    const attempt = 700 + index;
    await withRoot(async root => {
      await withFixture(
        async fixture => {
          await assert.rejects(
            () =>
              generateImageApi(root, source(attempt), 'build/u.png', {
                testOnly: { baseUrl: fixture.baseUrl },
              }),
            /unknown/i,
          );
          const first = await readJob(root, attempt);
          assert.equal(first.state, 'submit-unknown');
          assert.equal(first.submitted, 1);
          assert.equal(fixture.state.requests.length, 1);

          await assert.rejects(
            () =>
              generateImageApi(root, source(attempt), 'build/u.png', {
                testOnly: { baseUrl: fixture.baseUrl },
              }),
            /unknown|not resubmit/i,
          );
          assert.equal(fixture.state.requests.length, 1, `an ambiguous (${mode}) submit must never be retried`);
        },
        { mode },
      );
    });
  }
});

