/**
 * vllm-omni-image adapter contract tests — real local transport, real image bytes.
 *
 * These tests drive `generateImageApi` through a real Node HTTP fixture on
 * loopback (the adapter's documented test transport) that speaks the vLLM-Omni
 * synchronous image protocol (`POST /v1/images/generations` JSON and
 * `POST /v1/images/edits` multipart) and returns genuine PNG bytes encoded as
 * inline `b64_json`. They assert on the persisted
 * `.viscraft/jobs/image-api/<attempt>.json` records and the decoded output.
 *
 * High-risk invariants of the current Source and vllm-omni-image contract:
 *  - the `image-generation` Source carries a non-secret `endpoint` binding and
 *    no locality field; unknown Source fields are refused;
 *  - a succeeded `generate` decodes the inline base64 into a real PNG and
 *    records an `ImageGeneration` whose `outputSha256` matches the bytes;
 *  - image editing is a distinct operation: `edit` transmits the reference
 *    Asset only after explicit per-Asset `uploadAssets` consent, and omitting it
 *    throws BEFORE any request (the fixture receives zero requests);
 *  - a missing endpoint binding is a loud error naming the binding;
 *  - a configured credential env var is resolved at call time and sent, and a
 *    missing/invalid one is a loud error with no request;
 *  - the loopback-vs-remote authorization rule: loopback HTTP is permitted, a
 *    remote endpoint needs HTTPS and the explicit submit authorization;
 *  - an ambiguous submit (transport error / 5xx / malformed body) is never
 *    auto-resubmitted (the fixture request count stays 1);
 *  - the prompt text, the image bytes and the credential are never written into
 *    the job record or the returned generation record;
 *  - a zero-dimension raster size (`0x0`) is rejected.
 */

