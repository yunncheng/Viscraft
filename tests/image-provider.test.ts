test('the prompt text and the image bytes are never persisted', async () => {
  await withRoot(async root => {
    await withFixture(async fixture => {
      const png = await providerPng();
      const pngB64 = png.toString('base64');

      const generate = source(900);
      const generated = await generateImageApi(root, generate, 'build/g.png', {
        testOnly: { baseUrl: fixture.baseUrl },
      });
      const jobRaw = await readFile(join(root, JOB_FILE_REL(900)), 'utf8');
      assert.ok(!jobRaw.includes(generate.prompt), 'the prompt text must never be persisted');
      assert.ok(!jobRaw.includes('"prompt"'), 'no raw prompt field may be persisted');
      assert.ok(!jobRaw.includes(pngB64), 'the image bytes must never be persisted');
      const generationRaw = JSON.stringify(generated.generation);
      assert.ok(!generationRaw.includes(generate.prompt), 'the generation record must not carry the prompt');
      assert.ok(!generationRaw.includes(pngB64), 'the generation record must not carry the bytes');
      assert.ok(!generationRaw.includes('http'), 'the generation record must not carry a URL');
      assert.equal(typeof generated.generation.promptHash, 'string');

      const ref = await hero(root);
      const edit = source(901, {
        operation: 'edit',
        references: [{ asset: 'hero', category: 'image', role: 'identity' }],
      });
      const edited = await generateImageApi(root, edit, 'build/e.png', {
        endpoint: { protocol: 'vllm-omni-image', baseUrl: fixture.baseUrl },
        authorization: { submit: true, uploadAssets: ['hero'] },
        references: [ref],
      });
      const jobRaw2 = await readFile(join(root, JOB_FILE_REL(901)), 'utf8');
      const heroB64 = (await readFile(join(root, 'assets', 'hero.png'))).toString('base64');
      assert.ok(!jobRaw2.includes(heroB64), 'the transmitted reference bytes must never be persisted');
      assert.ok(!jobRaw2.includes(edit.prompt), 'the edit prompt must never be persisted');
      assert.ok(!JSON.stringify(edited.generation).includes(edit.prompt));
    });
  });
});

test('ImageApiError is exported and the adapter refuses an out-of-contract request', async () => {
  await withRoot(async root => {
    // A request that does not satisfy the canonical schema is refused at the boundary.
    const bogus = { ...source(1), kind: 'image' } as unknown as GenerateImageRequest;
    const error = await generateImageApi(root, bogus, 'build/x.png', {
      testOnly: { baseUrl: 'http://127.0.0.1:1' },
    }).then(
      () => null,
      (e: Error) => e,
    );
    assert.ok(error instanceof ImageApiError, 'the canonical-request re-validation must fail with ImageApiError');
    assert.match(error!.message, /image request/);
  });
});

test('the four image modes are separately expressible and reach distinct wire shapes', async () => {
  await withRoot(async root => {
    await withFixture(async fixture => {
      const ref = await hero(root, 'hero');
      // 1. text-to-image: generate, no references -> JSON generations endpoint.
      await generateImageApi(root, source(30, { operation: 'generate', references: [] }), 'build/t2i.png', {
        testOnly: { baseUrl: fixture.baseUrl },
      });
      // 2. image reference generation: generate WITH references -> multipart edits, image part(s).
      await generateImageApi(
        root,
        source(31, { operation: 'generate', references: [{ asset: 'hero', category: 'image', role: 'identity' }] }),
        'build/ref.png',
        { testOnly: { baseUrl: fixture.baseUrl }, references: [ref] },
      );
      // 3. image instruction edit: edit with a non-mask reference -> edits, no mask part.
      await generateImageApi(
        root,
        source(32, { operation: 'edit', references: [{ asset: 'hero', category: 'image', role: 'identity' }] }),
        'build/instr.png',
        { testOnly: { baseUrl: fixture.baseUrl }, references: [ref] },
      );
      // 4. image region edit: edit with a non-mask + a mask -> edits with a mask part.
      const mask = await hero(root, 'mask');
      await generateImageApi(
        root,
        source(33, {
          operation: 'edit',
          references: [
            { asset: 'hero', category: 'image', role: 'identity' },
            { asset: 'mask', category: 'image', role: 'mask' },
          ],
        }),
        'build/region.png',
        { testOnly: { baseUrl: fixture.baseUrl }, references: [ref, mask] },
      );

      assert.deepEqual(
        fixture.state.requests.map(request => request.path),
        ['/v1/images/generations', '/v1/images/edits', '/v1/images/edits', '/v1/images/edits'],
      );
      const refGen = fixture.state.requests[1].body.toString('latin1');
      assert.equal(
        (refGen.match(/name="image"/g) ?? []).length,
        1,
        'reference generation sends the conditioning image',
      );
      assert.equal(refGen.includes('name="mask_image"'), false);
      const instr = fixture.state.requests[2].body.toString('latin1');
      assert.equal((instr.match(/name="image"/g) ?? []).length, 1);
      assert.equal(instr.includes('name="mask_image"'), false, 'an instruction edit carries no region mask');
      const region = fixture.state.requests[3].body.toString('latin1');
      assert.equal((region.match(/name="image"/g) ?? []).length, 1);
      assert.equal(region.includes('name="mask_image"'), true, 'a region edit keeps its mask distinguishable');

      // Each mode is a distinct frozen request (operation + reference set).
      const jobs = await Promise.all([30, 31, 32, 33].map(attempt => readJob(root, attempt)));
      assert.deepEqual(
        jobs.map(job => job.operation),
        ['generate', 'generate', 'edit', 'edit'],
      );
      assert.equal(
        new Set(jobs.map(job => job.requestHash)).size,
        4,
        'the four modes must not share a request identity',
      );
    });
  });
});

