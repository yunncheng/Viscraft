test('a Build snapshot and the content store carry the generated provenance and parent bytes', async () => {
  await withRoot(async root => {
    await createProject(root, {
      title: 'Snapshot',
      output: { width: 64, height: 48, fps: { numerator: 25, denominator: 1 } },
    });
    await importReference(root, 'ref-a', 64);
    await withFixture(async fixture => {
      const edit: GenerateImageRequest = request({
        operation: 'edit',
        references: [{ asset: 'ref-a', category: 'image', role: 'identity' }],
      });
      const result = await generateImage(root, edit, testOnly(fixture.baseUrl));

      // Add a cheap simulated source so a real Build freezes the whole authored
      // tree (every Asset, including the generated image and its parent).
      const frames = 25;
      const project = await loadProject(root);
      await writeFile(
        join(root, 'project.json'),
        `${JSON.stringify(
          validateProject({
            ...project,
            sources: [
              {
                id: 'src_sim',
                kind: 'simulated',
                prompt: 'control chain',
                frames,
                seed: 0,
                attempt: 'snapshot_attempt',
                behavior: 'success',
              },
            ],
            composition: {
              ...project.composition,
              scenes: [{ id: 'scene_1', description: 'scene' }],
              shots: [{ id: 'shot_1', scene: 'scene_1', look: 'default', intent: 'shot', targetFrames: frames }],
              placements: [
                {
                  id: 'place_1',
                  shot: 'shot_1',
                  source: 'src_sim',
                  inFrame: 0,
                  outFrame: frames,
                  startFrame: 0,
                  audio: 'mute',
                },
              ],
            },
          }),
          null,
          2,
        )}\n`,
      );

      const build = await buildProject(root);
      assert.equal(build.status, 'succeeded', JSON.stringify(build.error));
      const snapshot = validateProject(
        JSON.parse(await readFile(join(root, '.viscraft', 'snapshots', `${build.id}.project.json`), 'utf8')),
      );
      const frozen = snapshot.assets.find(asset => asset.id === 'gen')!;
      assert.deepEqual(frozen.imageGeneration, result.asset.imageGeneration, 'the snapshot keeps the provenance');
      assert.deepEqual(frozen.inputs, result.asset.inputs, 'the snapshot keeps the parent relations');
      assert.ok(
        existsSync(join(root, '.viscraft', 'content', result.asset.sha256)),
        'the content store holds the generated bytes',
      );
      assert.ok(
        existsSync(join(root, '.viscraft', 'content', frozen.inputs![0].sha256)),
        'the content store holds the parent bytes',
      );

      // Export of the built project still applies one contract.
      const exportDir = join(root, 'output', 'project');
      await exportProject(root, exportDir);
      const exported = await loadProject(exportDir);
      assert.deepEqual(
        exported.assets.find(asset => asset.id === 'gen')!.imageGeneration,
        result.asset.imageGeneration,
      );
    });
  });
});
