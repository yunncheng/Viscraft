/**
 * E2 — portable hash-only provenance and real parent relations for generated
 * images.
 *
 * These tests drive a REAL loopback vllm-omni-image fixture returning genuine PNG
 * bytes, then prove that a generated/edited image Asset carries persistent
 * hash-only `imageGeneration` provenance and frozen `Asset.inputs` parent
 * relations, and that both survive registration → export → archive → restore.
 * They also prove the failure guarantees: a forged provenance is refused, a
 * changed parent is only reported (never an automatic redo), a frozen parent
 * identity is never rebound, and no secret / private job state enters a package.
 */
