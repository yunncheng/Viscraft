const MODEL = 'Study-Image';
const THIS_FILE = fileURLToPath(import.meta.url);

// A genuine 1x1 PNG (magic bytes + real container) — enough for the boundary.
const PNG = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAAC0lEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==',
  'base64',
);

const JOB_FILE = (root: string, sourceId: string, attempt: number): string =>
  join(root, `.viscraft/jobs/image-api/${sourceId}.${attempt}.json`);

function source(attempt: number, overrides: Partial<GenerateImageRequest> = {}): GenerateImageRequest {
  return {
    id: 's_img',
    attempt,
    asset: 'out_img',
    rights: { origin: 'generated by the vllm-omni-image fixture', license: 'CC0-1.0', redistributable: true },
    endpoint: 'test',
    operation: 'generate',
    model: MODEL,
    prompt: 'a lone lighthouse on a stormy basalt cliff at dusk',
    references: [],
    ...overrides,
  };
}

function imageAsset(id: string, path: string, sha256: string): Asset {
  return {
    id,
    revision: 1,
    path,
    sha256,
    type: 'image',
    rights: { origin: 'original test fixture', license: 'CC0-1.0', redistributable: true },
    simulated: false,
  };
}

function extension(
  imageFields: (
    source: GenerateImageRequest,
    parameters: Record<string, unknown>,
  ) => Record<string, string | number | boolean>,
  validate: (
    source: GenerateImageRequest,
    parameters: Record<string, unknown>,
    settings: Record<string, unknown>,
  ) => void = () => {},
): GenerationExtension {
  return {
    model: {
      id: MODEL,
      medium: 'image',
      parameters: z.object({ quality: z.enum(['fine', 'draft']).optional() }).strict(),
      validate() {},
    },
    mapping: { model: MODEL, protocol: 'vllm-omni-image', validate, imageFields },
    implementationFiles: [THIS_FILE],
  };
}

async function withRoot(fn: (root: string) => Promise<void>): Promise<void> {
  const root = await mkdtemp(join(tmpdir(), 'viscraft-image-proto-'));
  try {
    await fn(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

interface Fixture {
  baseUrl: string;
  requests: { path: string; body: Buffer }[];
  close: () => Promise<void>;
}

/** A loopback fixture that records every request and returns the embedded PNG. */
async function withFixture(fn: (fixture: Fixture) => Promise<void>): Promise<void> {
  const state = { requests: [] as { path: string; body: Buffer }[] };
  let port = 0;
  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    const path = new URL(req.url ?? '/', 'http://127.0.0.1').pathname;
    const chunks: Buffer[] = [];
    req.on('data', (c: Buffer) => chunks.push(c));
    req.on('end', () => {
      if (!(req.method === 'POST' && (path === '/v1/images/generations' || path === '/v1/images/edits'))) {
        res.writeHead(404);
        res.end('nf');
        return;
      }
      state.requests.push({ path, body: Buffer.concat(chunks) });
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ created: 1, data: [{ b64_json: PNG.toString('base64') }] }));
    });
  });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address();
  port = typeof address === 'object' && address ? address.port : 0;
  const fixture: Fixture = {
    baseUrl: `http://127.0.0.1:${port}`,
    requests: state.requests,
    close: () => new Promise<void>(r => server.close(() => r())),
  };
  try {
    await fn(fixture);
  } finally {
    await fixture.close();
  }
}

test('vllm-omni-image: scalar field map and ordered multipart parts for the three request shapes', async () => {
  const s = source(1, { size: '512x512', seed: 7 });

  // 1. no references -> the JSON generations body, protocol fields in canonical order.
  assert.deepEqual(Object.keys(vllmOmniImageFields(s, MODEL)), ['model', 'prompt', 'size', 'seed', 'response_format']);
  assert.deepEqual(vllmOmniImageJsonBody(s, MODEL), {
    model: MODEL,
    prompt: s.prompt,
    size: '512x512',
    seed: 7,
    response_format: 'b64_json',
  });

  // A mapping's scalar extras merge AFTER the protocol-owned fields.
  const mapped = vllmOmniImageFields(s, MODEL, { quality: 'high' });
  assert.deepEqual(Object.keys(mapped), ['model', 'prompt', 'size', 'seed', 'response_format', 'quality']);
  assert.equal(mapped.quality, 'high');

  // 2. references (no mask) -> ordered `image` parts, no mask part.
  const refForm = vllmOmniImageForm(s, MODEL, [
    { role: 'identity', mime: 'image/png', bytes: PNG },
    { role: 'environment', mime: 'image/png', bytes: PNG },
  ]);
  assert.equal(refForm.getAll('image').length, 2, 'both references are ordered image parts');
  assert.equal(refForm.get('mask_image'), null, 'a reference-only request carries no mask part');
  assert.deepEqual(
    (refForm.getAll('image') as File[]).map(file => file.name),
    ['reference.png', 'reference.png'],
  );
  assert.equal(refForm.get('prompt'), s.prompt);
  assert.equal(refForm.get('model'), MODEL);
  assert.equal(refForm.get('size'), '512x512');
  assert.equal(refForm.get('seed'), '7');
  assert.equal(refForm.get('response_format'), 'b64_json');
  assert.equal(refForm.get('quality'), null, 'no mapping extras are invented');

  // 3. with a mask -> one image part plus the mask part, in authored order.
  const maskForm = vllmOmniImageForm(s, MODEL, [
    { role: 'identity', mime: 'image/png', bytes: PNG },
    { role: 'mask', mime: 'image/png', bytes: PNG },
  ]);
  assert.equal(maskForm.getAll('image').length, 1, 'the non-mask reference stays an image part');
  assert.equal(
    (maskForm.get('mask_image') as File | null)?.name,
    'mask.png',
    'the mask reference becomes the mask_image part',
  );
  // The serialized multipart body preserves authored order: identity part, then mask.
  const maskBody = await new Response(maskForm).text();
  assert.ok(
    maskBody.indexOf('name="image"') < maskBody.indexOf('name="mask_image"'),
    'the identity part precedes the mask part',
  );

  // A JPEG reference keeps a jpg multipart filename.
  const jpegForm = vllmOmniImageForm(s, MODEL, [{ role: 'identity', mime: 'image/jpeg', bytes: PNG }]);
  assert.equal((jpegForm.get('image') as File).name, 'reference.jpg');
});

test('vllm-omni-image: request identity covers the route + scalar fields + ordered reference hashes only', () => {
  const s = source(2);
  const noRefs = vllmOmniImageRequestIdentity(s, MODEL, []) as {
    route: string;
    fields: unknown;
    references: unknown[];
  };
  const withRefs = vllmOmniImageRequestIdentity(s, MODEL, [{ role: 'identity', sha256: 'a'.repeat(64) }]) as {
    route: string;
    references: unknown[];
  };
  assert.equal(noRefs.route, '/v1/images/generations');
  assert.equal(withRefs.route, '/v1/images/edits');
  assert.deepEqual(withRefs.references, [{ category: 'image', role: 'identity', sha256: 'a'.repeat(64) }]);

  // The identity is a pure function of the encoded request: a changed scalar
  // field changes it; it carries no bytes, boundary or temp filename at all.
  assert.notEqual(
    stableHash(vllmOmniImageRequestIdentity(s, MODEL, [], { quality: 'high' })),
    stableHash(vllmOmniImageRequestIdentity(s, MODEL, [], { quality: 'low' })),
  );
  assert.equal(JSON.stringify(noRefs).includes('boundary'), false);
  assert.equal(JSON.stringify(noRefs).includes('.png'), false);
});

test('vllm-omni-image: mapping boundary refuses reserved keys, nested JSON and URL/inline-data scalars', () => {
  for (const reserved of ['model', 'prompt', 'image', 'mask_image', 'response_format']) {
    assert.throws(
      () => assertVllmOmniImageMapping({ [reserved]: 'x' }),
      new RegExp(`protocol-owned field '${reserved}'`),
    );
  }
  assert.throws(() => assertVllmOmniImageMapping({ quality: { nested: true } }), /nested JSON|scalar/);
  assert.throws(() => assertVllmOmniImageMapping({ quality: ['a', 'b'] }), /nested JSON|scalar/);
  assert.throws(() => assertVllmOmniImageMapping({ quality: null }), /nested JSON|scalar/);
  assert.throws(
    () => assertVllmOmniImageMapping({ callback: 'https://images.example.com/hook' }),
    /URL or inline data/,
  );
  assert.throws(() => assertVllmOmniImageMapping({ source: 'data:image/png;base64,AAAA' }), /URL or inline data/);
  assert.throws(() => assertVllmOmniImageMapping({ steps: Number.POSITIVE_INFINITY }), /finite number/);
  assert.doesNotThrow(() => assertVllmOmniImageMapping({ quality: 'high', steps: 4, guided: true }));
});

test('vllm-omni-image: response decode distinguishes malformed, empty, oversize and non-image', () => {
  const b64 = PNG.toString('base64');
  assert.deepEqual(decodeVllmOmniImageResponse(JSON.stringify({ created: 1, data: [{ b64_json: b64 }] }), 1024), {
    kind: 'image',
    bytes: PNG,
    mime: 'image/png',
  });
  assert.equal(decodeVllmOmniImageResponse('this is not json {', 1024).kind, 'malformed');
  assert.equal(
    decodeVllmOmniImageResponse(JSON.stringify({ data: [] }), 1024).kind,
    'malformed',
    'a 2xx body without a data entry is malformed',
  );
  assert.equal(
    decodeVllmOmniImageResponse(JSON.stringify({ data: [{ b64_json: '' }] }), 1024).kind,
    'malformed',
    'an empty b64_json is refused by the schema',
  );
  assert.equal(
    decodeVllmOmniImageResponse(
      JSON.stringify({ data: [{ b64_json: Buffer.from('not an image').toString('base64') }] }),
      1024,
    ).kind,
    'not-image',
  );
  assert.equal(decodeVllmOmniImageResponse(JSON.stringify({ data: [{ b64_json: b64 }] }), 4).kind, 'oversize');
});

test('vllm-omni-image: a reserved-field mapping is refused by the shared preflight AND the executor with zero requests', async () => {
  const reserved = extension(() => ({ prompt: 'override' }));
  const src = source(3);
  await withRoot(async root => {
    await withFixture(async fixture => {
      assert.throws(
        () => preflightImageEncoding(src, { extension: reserved, testOnly: { baseUrl: fixture.baseUrl } }),
        /protocol-owned field 'prompt'/,
      );
      await assert.rejects(
        () =>
          generateImageApi(root, src, 'build/x.png', {
            extension: reserved,
            testOnly: { baseUrl: fixture.baseUrl },
          }),
        /protocol-owned field 'prompt'/,
        'the executor runs the same preflight and must refuse identically',
      );
      assert.equal(fixture.requests.length, 0, 'a bad mapping must reach neither the network nor a host');
      assert.ok(!existsSync(join(root, '.viscraft', 'jobs', 'image-api')), 'a bad mapping must write no job record');
    });
  });
});

test("vllm-omni-image: validateImageServiceRequest is the executor's own mapping validation", async () => {
  const strict = extension(
    () => ({}),
    () => {
      throw new Error('This service supports fine quality only');
    },
  );
  const src = source(4);
  await withRoot(async root => {
    await withFixture(async fixture => {
      const error = (() => {
        try {
          validateImageServiceRequest(src, { extension: strict });
          return null;
        } catch (e) {
          return e as Error;
        }
      })();
      assert.ok(error, 'the shared validator must reject the request');
      assert.match(error!.message, /fine quality only/);
      await assert.rejects(
        () =>
          generateImageApi(root, src, 'build/x.png', {
            extension: strict,
            testOnly: { baseUrl: fixture.baseUrl },
          }),
        /fine quality only/,
        'the executor must surface the same validation failure',
      );
      assert.equal(fixture.requests.length, 0);
    });
  });
});

test('vllm-omni-image: the persisted request hash is bound to the encoded request, not to path/boundary noise', async () => {
  const qualityExtension = extension((_s, p) => ({ quality: p.quality === 'fine' ? 'high' : 'low' }));

  // (i) changing only the encoded scalar field changes the PERSISTED request hash.
  await withRoot(async rootA => {
    await withRoot(async rootB => {
      await withFixture(async fixture => {
        await generateImageApi(rootA, source(9, { parameters: { quality: 'fine' } }), 'build/a.png', {
          extension: qualityExtension,
          testOnly: { baseUrl: fixture.baseUrl },
        });
        await generateImageApi(rootB, source(9, { parameters: { quality: 'draft' } }), 'build/b.png', {
          extension: qualityExtension,
          testOnly: { baseUrl: fixture.baseUrl },
        });
        const jobA = JSON.parse(await readFile(JOB_FILE(rootA, 's_img', 9), 'utf8')) as { requestHash: string };
        const jobB = JSON.parse(await readFile(JOB_FILE(rootB, 's_img', 9), 'utf8')) as { requestHash: string };
        assert.notEqual(jobA.requestHash, jobB.requestHash, 'a different encoded field must change the frozen request');
      });
    });
  });

  // (ii) the same content from a different reference path (a different temp
  // filename) is STABLE: the attempt is recognised as the same frozen request and
  // re-materializes from the retained bytes without a second POST.
  await withRoot(async root => {
    await mkdir(join(root, 'assets'), { recursive: true });
    await writeFile(join(root, 'assets', 'hero.png'), PNG);
    await writeFile(join(root, 'assets', 'hero-copy.png'), PNG);
    const sha256 = createHash('sha256').update(PNG).digest('hex');
    const src = source(12, { operation: 'edit', references: [{ asset: 'hero', category: 'image', role: 'identity' }] });
    await withFixture(async fixture => {
      await generateImageApi(root, src, 'build/e1.png', {
        testOnly: { baseUrl: fixture.baseUrl },
        references: [{ asset: imageAsset('hero', 'assets/hero.png', sha256), root }],
      });
      const first = JSON.parse(await readFile(JOB_FILE(root, 's_img', 12), 'utf8')) as { requestHash: string };
      await generateImageApi(root, src, 'build/e2.png', {
        testOnly: { baseUrl: fixture.baseUrl },
        references: [{ asset: imageAsset('hero', 'assets/hero-copy.png', sha256), root }],
      });
      const second = JSON.parse(await readFile(JOB_FILE(root, 's_img', 12), 'utf8')) as { requestHash: string };
      assert.equal(
        first.requestHash,
        second.requestHash,
        'a reference path/temp filename must not change the frozen request',
      );
      assert.equal(fixture.requests.length, 1, 'the same frozen request re-materializes without a second POST');
    });
  });
});

test('vllm-omni-image: two different Sources that both use attempt 33 complete independently', async () => {
  await withRoot(async root => {
    await withFixture(async fixture => {
      // Two distinct Source ids each legitimately use the SAME numeric attempt.
      // Keying the job/lock/media on the bare attempt made the second collide with
      // the first; the Source-scoped stem must let both finish.
      const a = source(33, { id: 'shot_a', prompt: 'a storm over shot A' });
      const b = source(33, { id: 'shot_b', prompt: 'a storm over shot B' });
      const resultA = await generateImageApi(root, a, 'build/a.png', {
        testOnly: { baseUrl: fixture.baseUrl },
      });
      const resultB = await generateImageApi(root, b, 'build/b.png', {
        testOnly: { baseUrl: fixture.baseUrl },
      });

      assert.equal(fixture.requests.length, 2, 'each Source makes its own request');
      assert.ok(existsSync(JOB_FILE(root, 'shot_a', 33)), 'shot_a has its own job record');
      assert.ok(existsSync(JOB_FILE(root, 'shot_b', 33)), 'shot_b has its own job record');
      assert.ok(existsSync(join(root, 'build', 'a.png')), 'shot_a produced its artifact');
      assert.ok(existsSync(join(root, 'build', 'b.png')), 'shot_b produced its artifact');
      assert.notEqual(resultA.generation.requestHash, resultB.generation.requestHash, 'the two requests are distinct');

      // Status scans the jobs dir: both records remain listed, each with its Source id.
      const status = (await imageApiStatus(root)) as Array<{ sourceId: string; attempt: number }>;
      assert.deepEqual(status.map(job => `${job.sourceId}.${job.attempt}`).sort(), ['shot_a.33', 'shot_b.33']);
    });
  });
});
