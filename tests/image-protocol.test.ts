/**
 * Pure `vllm-omni-image` protocol contract tests.
 *
 * These tests exercise the extracted protocol module directly — its scalar field
 * map, multipart part construction, request identity and response decode — and
 * prove that the read-only preflight (`validateImageServiceRequest` /
 * `preflightImageEncoding`) is the SAME code path the executor
 * (`generateImageApi`) runs, so a bad image request is rejected identically by
 * Plan and Produce with zero network calls.
 *
 * The tests are deliberately byte-thin: reference bytes are a tiny embedded PNG
 * whose magic bytes satisfy the boundary, and only the identity/hash assertions
 * are compared — never a base64 payload.
 */

