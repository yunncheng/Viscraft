// --- axis 2: loopback boundary -------------------------------------------
test('endpoint boundary: every non-loopback / credentialed / shaped URL is refused with no job', async () => {
  const cases: [string, RegExp][] = [
    ['http://example.com', /loopback/i],
    ['http://localhost:8000', /loopback/i],
    ['http://127.0.0.1.evil.com:8000', /loopback/i],
    ['http://0.0.0.0:8000', /loopback/i],
    ['http://[::ffff:127.0.0.1]:8000', /loopback/i],
    ['http://user:pass@127.0.0.1:8000', /credential/i],
    ['http://example.com@127.0.0.1:8000', /credential/i],
    // A loopback HTTPS endpoint is permitted transport, so the submit gate is
    // the thing that refuses an unauthorized call (never a silent request).
    ['https://127.0.0.1:8443', /authorization/i],
    // A base URL path is permitted (mirrors the video adapter); the gate refuses.
    ['http://127.0.0.1:8000/v1/images', /authorization/i],
    ['http://127.0.0.1:8000/?x=1', /query|fragment/i],
    ['http://127.0.0.1:8000/#frag', /query|fragment/i],
  ];
  let attempt = 200;
  for (const [url, re] of cases) {
    await withRoot(async root => {
      await assert.rejects(() => generateImageApi(root, src(attempt), 'build/o.png', ep(url)), re, `baseUrl=${url}`);
      assert.ok(!existsSync(join(root, JOB(attempt))), `no job record for ${url}`);
    });
    attempt += 1;
  }
});

