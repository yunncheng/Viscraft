test('schema edges: size / seed / attempt / prompt length / conditionals', () => {
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { size: '512x512' })).success, true);
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { size: 'auto' })).success, false);
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { size: '512' })).success, false);
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { size: '512X512' })).success, false);
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { size: '123456x1' })).success, false, 'six digits');
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { size: '0x0' })).success, false, '0x0 is now rejected');
  assert.equal(
    GenerateImageRequestSchema.safeParse(src(1, { size: '0x512' })).success,
    false,
    'zero width is rejected',
  );

  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { seed: -1 })).success, false, 'negative seed');
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { seed: 1.5 })).success, false, 'fractional seed');
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { seed: 0 })).success, true);

  assert.equal(GenerateImageRequestSchema.safeParse(src(0)).success, false, 'attempt zero');
  assert.equal(GenerateImageRequestSchema.safeParse(src(-1)).success, false);
  assert.equal(GenerateImageRequestSchema.safeParse(src(1.5)).success, false);

  assert.equal(
    GenerateImageRequestSchema.safeParse(
      src(1, { operation: 'edit', references: [{ asset: 'm', category: 'image', role: 'mask' }] }),
    ).success,
    false,
    'edit with only a mask reference',
  );
  assert.equal(
    GenerateImageRequestSchema.safeParse(
      src(1, { operation: 'edit', references: [identity('p'), { asset: 'm', category: 'image', role: 'mask' }] }),
    ).success,
    true,
  );
  assert.equal(
    GenerateImageRequestSchema.safeParse(src(1, { operation: 'generate', references: [identity('p')] })).success,
    true,
    'multi-reference generate is legal',
  );
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { prompt: 'x' })).success, true, '1-char prompt');
  assert.equal(
    GenerateImageRequestSchema.safeParse(src(1, { prompt: 'x'.repeat(20000) })).success,
    true,
    '20000-char prompt',
  );
  assert.equal(
    GenerateImageRequestSchema.safeParse(src(1, { prompt: 'x'.repeat(20001) })).success,
    false,
    '20001-char prompt',
  );
  assert.equal(GenerateImageRequestSchema.safeParse(src(1, { prompt: '' })).success, false, 'empty prompt');
  // The removed locality identity is refused as an unknown field.
  assert.equal(
    GenerateImageRequestSchema.safeParse({ ...src(1), provider: 'local-image' }).success,
    false,
    'a provider field is refused',
  );
});

test('schema edges: ImageGeneration provenance is not capped by any model reference count', () => {
  const base = {
    provider: 'vllm-omni-image',
    model: 'm',
    operation: 'generate',
    promptHash: 'a'.repeat(64),
    requestHash: 'b'.repeat(64),
    outputSha256: 'c'.repeat(64),
    simulated: true,
  };
  // The general contract must be able to record a legal request for any image
  // model, so provenance hash counts are independent of any one model's
  // reference limit. A 13- and a 40-reference record both parse.
  assert.equal(
    ImageGenerationSchema.safeParse({ ...base, inputSha256: Array.from({ length: 13 }, () => 'd'.repeat(64)) }).success,
    true,
    '13 input hashes',
  );
  assert.equal(
    ImageGenerationSchema.safeParse({ ...base, inputSha256: Array.from({ length: 40 }, () => 'd'.repeat(64)) }).success,
    true,
    '40 input hashes',
  );
  assert.equal(ImageGenerationSchema.safeParse({ ...base, seed: -5 }).success, false, 'negative seed');
});

test('preflight: a missing or non-image ordered reference is reported clearly', async () => {
  await withRoot(async root => {
    await createProject(root, { title: 'refs' });
    const base: GenerateImageRequest = {
      id: 's',
      attempt: 1,
      asset: 'out',
      rights: { origin: 'o', license: 'CC0-1.0', redistributable: true },
      endpoint: 'test',
      operation: 'edit',
      model: 'm',
      prompt: 'x',
      references: [identity('nope')],
    };
    const config = {
      providers: {
        imageApi: {
          test: {
            endpoint: { protocol: 'vllm-omni-image' as const, baseUrl: 'http://127.0.0.1:9' },
            authorization: { submit: true },
          },
        },
      },
    };
    // A declared image reference that does not exist in the Project.
    const missing = await preflightGenerateImage(root, base, config);
    assert.equal(missing.ok, false);
    assert.ok(
      missing.issues.some(issue => issue.code === 'reference-invalid' && /does not exist/.test(issue.message)),
      `expected a missing-reference issue, got ${JSON.stringify(missing.issues)}`,
    );

    // A reference that points at a non-image Asset.
    const video: Asset = {
      id: 'v',
      revision: 1,
      path: 'v.mp4',
      sha256: 'a'.repeat(64),
      type: 'video',
      rights: { origin: 'o', license: 'CC0-1.0', redistributable: true },
      simulated: false,
    };
    await addAsset(root, video);
    const wrong = await preflightGenerateImage(root, { ...base, references: [identity('v')] }, config);
    assert.equal(wrong.ok, false);
    assert.ok(
      wrong.issues.some(issue => issue.code === 'reference-invalid' && /image references only/.test(issue.message)),
      `expected a non-image-reference issue, got ${JSON.stringify(wrong.issues)}`,
    );
  });
});
