const identity = (asset: string) => ({ asset, category: 'image' as const, role: 'identity' as const });

/** A production loopback `vllm-omni-image` endpoint binding pointing at `baseUrl`. */
const ep = (baseUrl: string) => ({ endpoint: { protocol: 'vllm-omni-image' as const, baseUrl } });

async function providerPng(): Promise<Buffer> {
  const dir = await mkdtemp(join(tmpdir(), 'vcv-png-'));
  const file = join(dir, 'g.png');
  try {
    await runCommand('ffmpeg', [
      '-y',
      '-hide_banner',
      '-loglevel',
      'error',
      '-threads',
      '1',
      '-f',
      'lavfi',
      '-i',
      'testsrc2=size=96x64:rate=1:duration=1',
      '-frames:v',
      '1',
      '-pix_fmt',
      'rgb24',
      file,
    ]);
    return await readFile(file);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}
async function writePng(dir: string, name: string, size: number): Promise<void> {
  await mkdir(dir, { recursive: true });
  await runCommand('ffmpeg', [
    '-y',
    '-hide_banner',
    '-loglevel',
    'error',
    '-threads',
    '1',
    '-f',
    'lavfi',
    '-i',
    `testsrc2=size=${size}x${size}:rate=1:duration=1`,
    '-frames:v',
    '1',
    '-pix_fmt',
    'rgb24',
    join(dir, name),
  ]);
}
function imageAsset(id: string, path: string, sha256: string): Asset {
  return {
    id,
    revision: 1,
    path,
    sha256,
    type: 'image',
    rights: { origin: 'original FFmpeg fixture', license: 'CC0-1.0', redistributable: true },
    simulated: false,
  };
}
async function hero(root: string, id = 'hero', size = 64): Promise<{ asset: Asset; root: string }> {
  await writePng(join(root, 'assets'), `${id}.png`, size);
  const sha256 = await hashFile(join(root, 'assets', `${id}.png`));
  return { asset: imageAsset(id, `assets/${id}.png`, sha256), root };
}

/** Register an Asset into the Project so an image request may reference it. */
async function addAsset(root: string, asset: Asset): Promise<void> {
  const file = join(root, 'project.json');
  const project = JSON.parse(await readFile(file, 'utf8')) as { assets: Asset[]; revision: number };
  project.assets.push(asset);
  project.revision += 1;
  await writeFile(file, JSON.stringify(project, null, 2));
}

type Mode =
  | 'ok'
  | 'http500'
  | 'http400'
  | 'http404'
  | 'http422'
  | 'http408'
  | 'http429'
  | 'redirect302'
  | 'network'
  | 'malformed'
  | 'emptydata'
  | 'emptyb64'
  | 'nonimage';
interface Fixture {
  baseUrl: string;
  state: { requests: { method: string; path: string; body: Buffer }[] };
  close: () => Promise<void>;
}

async function withFixture(fn: (f: Fixture) => Promise<void>, mode: Mode = 'ok'): Promise<void> {
  const png = await providerPng();
  const state = { requests: [] as { method: string; path: string; body: Buffer }[] };
  let port = 0;
  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    const path = new URL(req.url ?? '/', 'http://127.0.0.1').pathname;
    const chunks: Buffer[] = [];
    req.on('data', (c: Buffer) => chunks.push(c));
    req.on('end', () => {
      if (!(req.method === 'POST' && (path === '/v1/images/generations' || path === '/v1/images/edits'))) {
        res.writeHead(404);
        res.end('nf');
        return;
      }
      state.requests.push({ method: req.method ?? '', path, body: Buffer.concat(chunks) });
      const json = (status: number, body: string) => {
        res.writeHead(status, { 'content-type': 'application/json' });
        res.end(body);
      };
      if (mode === 'network') {
        req.socket?.destroy();
        return;
      }
      if (mode === 'http500') return json(500, '{"detail":"internal"}');
      if (mode === 'http400') return json(400, '{"detail":"bad"}');
      if (mode === 'http404') return json(404, '{"detail":"nf"}');
      if (mode === 'http422') return json(422, '{"detail":"unprocessable"}');
      if (mode === 'http408') return json(408, '{"detail":"timeout"}');
      if (mode === 'http429') return json(429, '{"detail":"slow down"}');
      if (mode === 'redirect302') {
        res.writeHead(302, { location: '/elsewhere' });
        res.end();
        return;
      }
      if (mode === 'malformed') return json(200, 'this is not json {');
      if (mode === 'emptydata') return json(200, JSON.stringify({ created: 1, data: [] }));
      if (mode === 'emptyb64') return json(200, JSON.stringify({ created: 1, data: [{ b64_json: '' }] }));
      if (mode === 'nonimage')
        return json(
          200,
          JSON.stringify({ created: 1, data: [{ b64_json: Buffer.from('not an image at all').toString('base64') }] }),
        );
      return json(200, JSON.stringify({ created: 1728000000, data: [{ b64_json: png.toString('base64') }] }));
    });
  });
  await new Promise<void>(r => server.listen(0, '127.0.0.1', r));
  const addr = server.address();
  port = typeof addr === 'object' && addr ? addr.port : 0;
  const f: Fixture = {
    baseUrl: `http://127.0.0.1:${port}`,
    state,
    close: () => new Promise<void>(r => server.close(() => r())),
  };
  try {
    await fn(f);
  } finally {
    await f.close();
  }
}
async function withRoot(fn: (root: string) => Promise<void>): Promise<void> {
  const root = await mkdtemp(join(tmpdir(), 'vcv-root-'));
  try {
    await fn(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}
async function readJob(root: string, a: number): Promise<Record<string, unknown>> {
  return JSON.parse(await readFile(join(root, JOB(a)), 'utf8')) as Record<string, unknown>;
}

