// --- axis 4: leakage ------------------------------------------------------
async function walk(dir: string, base = dir): Promise<string[]> {
  const out: string[] = [];
  for (const name of await readdir(dir)) {
    const p = join(dir, name);
    const s = await stat(p);
    if (s.isDirectory()) out.push(...(await walk(p, base)));
    else out.push(p);
  }
  return out;
}

test('leakage: prompt text and provider base64 appear in no file; error paths leak neither', async () => {
  await withRoot(async root => {
    await withFixture(async f => {
      const png = await providerPng();
      const b64 = png.toString('base64');
      // A successful generate and an authorized edit.
      await generateImageApi(root, src(600, { size: '512x512', seed: 7 }), 'build/g.png', {
        testOnly: { baseUrl: f.baseUrl },
      });
      const ref = await hero(root);
      await generateImageApi(root, src(601, { operation: 'edit', references: [identity('hero')] }), 'build/e.png', {
        ...ep(f.baseUrl),
        authorization: { submit: true, uploadAssets: ['hero'] },
        references: [ref],
      });

      const files = await walk(root);
      const promptHits: string[] = [],
        b64Hits: string[] = [],
        rawHits: string[] = [];
      for (const p of files) {
        const buf = await readFile(p);
        const text = buf.toString('utf8');
        if (text.includes(PROMPT)) promptHits.push(p);
        if (buf.toString('latin1').includes(b64)) b64Hits.push(p);
        if (buf.includes(Buffer.from([0x89, 0x50, 0x4e, 0x47]))) rawHits.push(p);
      }
      assert.deepEqual(promptHits, [], `prompt leaked in: ${promptHits.join(', ')}`);
      assert.deepEqual(b64Hits, [], `base64 leaked in: ${b64Hits.join(', ')}`);
      // Raw PNG bytes may only live in the decoded image outputs, never in JSON records.
      for (const p of rawHits) assert.ok(!p.endsWith('.json'), `raw image bytes in a JSON record: ${p}`);
    });
  });
});

test('leakage: failure error strings never contain the prompt or provider bytes', async () => {
  await withRoot(async root => {
    await withFixture(async f => {
      const ref = await hero(root);
      // Settle each probe at creation. The consent gate refuses WITHOUT any I/O, so an
      // eagerly-created rejecting promise would surface as an unhandled rejection before
      // the loop below attaches a handler — a window that did not exist when the refusal
      // only arrived after a network round trip.
      const probes: Array<Promise<Error | null>> = [
        // Consented edit: really transmits, so the service's own HTTP 400 body is covered.
        generateImageApi(root, src(610, { operation: 'edit', references: [identity('hero')] }), 'build/o.png', {
          ...ep(f.baseUrl),
          authorization: { submit: true, uploadAssets: ['hero'] },
          references: [ref],
        }).then(
          () => null,
          (x: Error) => x,
        ),
        // Missing per-Asset consent: the refusal message itself must leak nothing.
        generateImageApi(root, src(611), 'build/o.png', ep(f.baseUrl)).then(
          () => null,
          (x: Error) => x,
        ),
      ];
      for (const p of probes) {
        const e = await p;
        assert.ok(e);
        assert.ok(!e!.message.includes(PROMPT), 'error message must not carry the prompt');
        assert.ok(!e!.message.includes('iVBOR'), 'error message must not carry base64 image data');
      }
      assert.equal(f.state.requests.length, 1, 'only the consented edit reached the service');
    }, 'http400');
  });
});

