test('every non-submittable attempt state is blocked with its own reason and no POST', async () => {
  // `failed` (a definitive 4xx) — blocked, POST stays at the one that failed.
  await withRoot(async root => {
    await createProject(root, { title: 'Failed' });
    await withFixture(
      async fixture => {
        await assert.rejects(
          () => generateImage(root, request(), testOnly(fixture.baseUrl)),
          /did not produce a usable image/i,
        );
        assert.equal(fixture.requests.length, 1);
        const check = await preflightGenerateImage(root, request(), testOnly(fixture.baseUrl));
        assert.equal(check.action, 'blocked');
        assert.ok(
          check.issues.some(issue => issue.code === 'attempt-failed'),
          JSON.stringify(check.issues),
        );
        await assert.rejects(() => generateImage(root, request(), testOnly(fixture.baseUrl)), /attempt-failed/i);
        assert.equal(fixture.requests.length, 1, 'a permanent failure is never resubmitted');
      },
      { status: 400 },
    );
  });

  // `submit-unknown` (a 5xx) — blocked, never auto-resubmitted.
  await withRoot(async root => {
    await createProject(root, { title: 'Unknown' });
    await withFixture(
      async fixture => {
        await assert.rejects(() => generateImage(root, request(), testOnly(fixture.baseUrl)), /unknown/i);
        assert.equal(fixture.requests.length, 1);
        const check = await preflightGenerateImage(root, request(), testOnly(fixture.baseUrl));
        assert.equal(check.action, 'blocked');
        assert.ok(
          check.issues.some(issue => issue.code === 'submit-unknown'),
          JSON.stringify(check.issues),
        );
        await assert.rejects(() => generateImage(root, request(), testOnly(fixture.baseUrl)), /submit-unknown/i);
        assert.equal(fixture.requests.length, 1, 'an unknown submit is never resubmitted');
      },
      { status: 500 },
    );
  });

  // The adapter's last-moment pre-submit guard: a refusal sends nothing and
  // leaves the attempt legally `created` (never an ambiguous `submitting`).
  await withRoot(async root => {
    await createProject(root, { title: 'Guard' });
    await withFixture(async fixture => {
      await assert.rejects(
        () =>
          generateImageApi(root, request(), '.viscraft/scratch/g/1/image', {
            testOnly: { baseUrl: fixture.baseUrl },
            assertSubmitAllowed: async () => {
              throw new Error('target occupied by a concurrent author edit');
            },
          }),
        /target occupied by a concurrent author edit/,
      );
      assert.equal(fixture.requests.length, 0, 'a refused pre-submit guard sends ZERO POSTs');
      const job = JSON.parse(await readFile(join(root, JOB('req', 1)), 'utf8')) as {
        state: string;
        submitted: number;
      };
      assert.equal(job.state, 'created', 'a refused guard leaves the attempt legally created');
      assert.equal(job.submitted, 0);
    });
  });

  // `submitting` (an interrupted submit) — blocked, neither submittable nor resumable.
  await withRoot(async root => {
    await createProject(root, { title: 'Interrupted' });
    await withFixture(async fixture => {
      await generateImage(root, request(), testOnly(fixture.baseUrl));
      assert.equal(fixture.requests.length, 1);
      await patchRecord(root, 'req', 1, {
        state: 'submitting',
        submitted: 1,
        outputPath: undefined,
        outputSha256: undefined,
      });
      const check = await preflightGenerateImage(root, request(), testOnly(fixture.baseUrl));
      assert.equal(check.action, 'blocked');
      assert.ok(
        check.issues.some(issue => issue.code === 'attempt-interrupted'),
        JSON.stringify(check.issues),
      );
      await assert.rejects(() => generateImage(root, request(), testOnly(fixture.baseUrl)), /attempt-interrupted/i);
      assert.equal(fixture.requests.length, 1, 'an interrupted submit is never resubmitted');
    });
  });
});

