const RIGHTS = { origin: 'generated by the vllm-omni-image fixture', license: 'CC0-1.0', redistributable: true };

async function withRoot(fn: (root: string) => Promise<void>): Promise<void> {
  const root = await mkdtemp(join(tmpdir(), 'viscraft-generate-image-'));
  try {
    await fn(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

/** A real PNG of `size`x`size` (distinct bytes per size). */
async function makePng(path: string, size = 64): Promise<void> {
  await mkdir(join(path, '..'), { recursive: true });
  await runCommand('ffmpeg', [
    '-y',
    '-hide_banner',
    '-loglevel',
    'error',
    '-threads',
    '1',
    '-f',
    'lavfi',
    '-i',
    `testsrc2=size=${size}x${size}:rate=1:duration=1`,
    '-frames:v',
    '1',
    '-pix_fmt',
    'rgb24',
    path,
  ]);
}

let cachedPng: Promise<Buffer> | undefined;
function providerPng(): Promise<Buffer> {
  cachedPng ??= (async () => {
    const dir = await mkdtemp(join(tmpdir(), 'viscraft-generate-image-png-'));
    const file = join(dir, 'g.png');
    try {
      await makePng(file, 96);
      return await readFile(file);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  })();
  return cachedPng;
}

function sha256(bytes: Buffer): string {
  return createHash('sha256').update(bytes).digest('hex');
}

interface Fixture {
  baseUrl: string;
  requests: { path: string; body: Buffer }[];
  close: () => Promise<void>;
}

/**
 * A real loopback vllm-omni-image fixture. By default it returns a genuine PNG; a
 * `status` other than 200 returns that status so the adapter classifies a
 * definitive 4xx as `failed` and a 5xx as `submit-unknown`.
 */
async function withFixture(fn: (fixture: Fixture) => Promise<void>, options: { status?: number } = {}): Promise<void> {
  const png = await providerPng();
  const status = options.status ?? 200;
  const requests: { path: string; body: Buffer }[] = [];
  let port = 0;
  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    const path = new URL(req.url ?? '/', 'http://127.0.0.1').pathname;
    const chunks: Buffer[] = [];
    req.on('data', (chunk: Buffer) => chunks.push(chunk));
    req.on('end', () => {
      if (!(req.method === 'POST' && (path === '/v1/images/generations' || path === '/v1/images/edits'))) {
        res.writeHead(404);
        res.end('nf');
        return;
      }
      requests.push({ path, body: Buffer.concat(chunks) });
      if (status !== 200) {
        res.writeHead(status, { 'content-type': 'application/json' });
        res.end(JSON.stringify({ error: 'provider error' }));
        return;
      }
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ created: 1, data: [{ b64_json: png.toString('base64') }] }));
    });
  });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address();
  port = typeof address === 'object' && address ? address.port : 0;
  const fixture: Fixture = {
    baseUrl: `http://127.0.0.1:${port}`,
    requests,
    close: () => new Promise<void>(r => server.close(() => r())),
  };
  try {
    await fn(fixture);
  } finally {
    await fixture.close();
  }
}

interface DrivenFixture extends Fixture {
  /** Resolves as soon as the provider receives a POST (before it responds). */
  waitForPost: () => Promise<void>;
  /** Let the held POST response return. */
  release: () => void;
}

/**
 * A loopback fixture that HOLDS its response until `release()`. This opens the
 * real window between the adapter's POST and its registration, so a test can
 * concurrently occupy the target id and drive a genuine registration exception.
 */
async function withDrivenFixture(fn: (fixture: DrivenFixture) => Promise<void>): Promise<void> {
  const png = await providerPng();
  const requests: { path: string; body: Buffer }[] = [];
  let seenResolve: () => void = () => {};
  const seen = new Promise<void>(r => {
    seenResolve = r;
  });
  let releaseResolve: () => void = () => {};
  const gate = new Promise<void>(r => {
    releaseResolve = r;
  });
  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    const path = new URL(req.url ?? '/', 'http://127.0.0.1').pathname;
    const chunks: Buffer[] = [];
    req.on('data', (chunk: Buffer) => chunks.push(chunk));
    req.on('end', () => {
      if (!(req.method === 'POST' && (path === '/v1/images/generations' || path === '/v1/images/edits'))) {
        res.writeHead(404);
        res.end('nf');
        return;
      }
      requests.push({ path, body: Buffer.concat(chunks) });
      seenResolve();
      void gate.then(() => {
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end(JSON.stringify({ created: 1, data: [{ b64_json: png.toString('base64') }] }));
      });
    });
  });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address();
  const port = typeof address === 'object' && address ? address.port : 0;
  const fixture: DrivenFixture = {
    baseUrl: `http://127.0.0.1:${port}`,
    requests,
    waitForPost: () =>
      new Promise<void>((resolve, reject) => {
        const timer = setTimeout(() => reject(new Error('fixture never received a POST')), 5000);
        seen.then(
          () => {
            clearTimeout(timer);
            resolve();
          },
          error => {
            clearTimeout(timer);
            reject(error);
          },
        );
      }),
    release: () => releaseResolve(),
    close: () => new Promise<void>(r => server.close(() => r())),
  };
  try {
    await fn(fixture);
  } finally {
    releaseResolve();
    await fixture.close();
  }
}

function request(overrides: Partial<GenerateImageRequest> = {}): GenerateImageRequest {
  return {
    id: 'req',
    attempt: 1,
    asset: 'out',
    rights: RIGHTS,
    endpoint: 'test',
    operation: 'generate',
    model: 'Qwen-Image',
    prompt: 'a lone lighthouse on a stormy basalt cliff at dusk',
    references: [],
    ...overrides,
  };
}

const testOnly = (baseUrl: string) => ({ providers: { imageApi: { test: { testOnly: { baseUrl } } } } });

const JOB = (id: string, attempt: number) => `.viscraft/jobs/image-api/${id}.${attempt}.json`;
const LOCK = (id: string, attempt: number) => `.viscraft/jobs/image-api/${id}.${attempt}.lock`;
const ORIGINAL = (id: string, attempt: number) => `.viscraft/provider-media/image-api-${id}.${attempt}.png`;

/** Patch a persisted attempt record in place (drives the non-submittable states). */
async function patchRecord(root: string, id: string, attempt: number, patch: Record<string, unknown>): Promise<void> {
  const file = join(root, JOB(id, attempt));
  const job = JSON.parse(await readFile(file, 'utf8')) as Record<string, unknown>;
  for (const [key, value] of Object.entries(patch)) {
    if (value === undefined) delete job[key];
    else job[key] = value;
  }
  await writeFile(file, `${JSON.stringify(job, null, 2)}\n`);
}

test('preflight reports configuration and authorization without submitting or writing', async () => {
  await withRoot(async root => {
    await createProject(root, { title: 'Preflight' });
    await withFixture(async fixture => {
      // No endpoint configured at all -> needs configuration.
      const unconfigured = await preflightGenerateImage(root, request(), {});
      assert.equal(unconfigured.ok, false);
      assert.ok(unconfigured.issues.some(issue => issue.code === 'image-endpoint-not-configured'));
      assert.equal(unconfigured.action, 'blocked');

      // A loopback production endpoint without the explicit submit authorization.
      const unauthorized = await preflightGenerateImage(root, request(), {
        providers: { imageApi: { test: { endpoint: { protocol: 'vllm-omni-image', baseUrl: fixture.baseUrl } } } },
      });
      assert.equal(unauthorized.ok, false);
      assert.ok(unauthorized.issues.some(issue => issue.code === 'image-submit-not-authorized'));

      // A ready request: reported as submittable, with the frozen request hash.
      const ready = await preflightGenerateImage(root, request(), testOnly(fixture.baseUrl));
      assert.equal(ready.ok, true, JSON.stringify(ready.issues));
      assert.equal(ready.action, 'submit');
      assert.match(ready.requestHash!, /^[a-f0-9]{64}$/);

      assert.equal(fixture.requests.length, 0, 'a preflight never reaches the service');
      assert.equal(existsSync(join(root, '.viscraft', 'jobs')), false, 'a preflight writes no job record');
    });
  });
});

test('success registers an author-area Asset, retains the provider original and persists the request record', async () => {
  await withRoot(async root => {
    await createProject(root, { title: 'Register' });
    await withFixture(async fixture => {
      const result = await generateImage(root, request(), testOnly(fixture.baseUrl));
      assert.equal(fixture.requests.length, 1);
      assert.equal(fixture.requests[0].path, '/v1/images/generations');

      // The returned Asset is the requested id at a legal author path.
      assert.equal(result.asset.id, 'out');
      assert.equal(result.asset.type, 'image');
      assert.equal(result.asset.simulated, true, 'a test-only run is simulated');
      assert.ok(result.asset.path.startsWith('assets/'), `author path, got ${result.asset.path}`);
      assert.equal(await hashFile(join(root, result.asset.path)), result.asset.sha256);
      assert.equal(result.asset.sha256, sha256(await providerPng()));

      // The Asset is registered in the Project.
      const project = await loadProject(root);
      assert.ok(project.assets.some(asset => asset.id === 'out' && asset.sha256 === result.asset.sha256));

      // Provider original retained + hashed; the request record persisted.
      const original = join(root, ORIGINAL('req', 1));
      assert.ok(existsSync(original), 'the provider original must be retained');
      assert.equal(await hashFile(original), result.asset.sha256);
      assert.equal(result.request.originalPath, ORIGINAL('req', 1));
      assert.equal(result.request.record, JOB('req', 1));
      const job = JSON.parse(await readFile(join(root, JOB('req', 1)), 'utf8')) as {
        state: string;
        requestHash: string;
      };
      assert.equal(job.state, 'succeeded');
      assert.equal(job.requestHash, result.request.hash);

      // Provenance is verifiable: request hash + parent hashes + provider/model.
      assert.equal(result.generation.provider, 'vllm-omni-image');
      assert.equal(result.generation.model, 'Qwen-Image');
      assert.deepEqual(result.generation.inputSha256, []);
      assert.match(result.generation.requestHash, /^[a-f0-9]{64}$/);
    });
  });
});

