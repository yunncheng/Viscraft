/**
 * `generate-image` operation contract tests.
 *
 * These tests drive a REAL loopback vllm-omni-image fixture that returns genuine PNG
 * bytes, so the whole chain is exercised: the read-only preflight, the frozen
 * request record + per-attempt lock, the retained provider original, author-area
 * registration, conflict refusal, repeat-returns-same, and recovery after a
 * registration failure without a second generation.
 *
 * E1 proves the PREFLIGHT and the EXECUTION share one judgement: the POST counts
 * are asserted (never just "it threw"), a target id occupied WITHOUT a matching
 * success record is refused before submission in both paths, a changed request is
 * refused by both, every non-submittable attempt state is blocked, and a real
 * registration exception (a concurrent occupation during the POST window) leaves
 * the succeeded original, the record and the existing Asset/author state intact so
 * the SAME succeeded request can finish registration against a free target id.
 */
