test('recovery: a succeeded-but-unregistered request completes registration without regenerating', async () => {
  await withRoot(async root => {
    await createProject(root, { title: 'Recovery' });
    await withFixture(async fixture => {
      // Simulate the crash window: the submission + retention succeeded, but the
      // process died before registration (the adapter is the operation's step 1-3).
      const submission = await generateImageApi(root, request(), '.viscraft/scratch/t/1/image', {
        testOnly: { baseUrl: fixture.baseUrl },
      });
      assert.equal(fixture.requests.length, 1);
      assert.ok(existsSync(join(root, ORIGINAL('req', 1))), 'the provider original was retained');
      assert.equal(
        (await loadProject(root)).assets.some(asset => asset.id === 'out'),
        false,
      );

      // The preflight classifies the unregistered success as resumable (not a
      // new submit).
      const check = await preflightGenerateImage(root, request(), testOnly(fixture.baseUrl));
      assert.equal(check.action, 'resume-registration');
      assert.equal(check.target.exists, false);

      // Re-running the SAME request completes registration from the persisted
      // success record + retained original, with NO second generation.
      const result = await generateImage(root, request(), testOnly(fixture.baseUrl));
      assert.equal(fixture.requests.length, 1, 'recovery must not regenerate');
      assert.equal(result.asset.sha256, submission.generation.outputSha256);
      assert.ok(
        (await loadProject(root)).assets.some(asset => asset.id === 'out' && asset.sha256 === result.asset.sha256),
      );
    });
  });
});

test('a real registration exception preserves the original, the record, the existing Asset and author state; the same request recovers with no second POST', async () => {
  await withRoot(async root => {
    await createProject(root, { title: 'RegistrationThrow' });
    const expectedSha = sha256(await providerPng());
    await withDrivenFixture(async fixture => {
      // Occupy a genuinely different Asset concurrently, DURING the POST window:
      // both of the operation's pre-submit checks have already passed by the time
      // the provider receives the request.
      const pending = generateImage(root, request(), testOnly(fixture.baseUrl));
      await fixture.waitForPost();
      assert.equal(fixture.requests.length, 1, 'the first POST was sent after the target checks passed');

      const before = await loadProject(root);
      const otherDir = await mkdtemp(join(tmpdir(), 'viscraft-generate-image-race-'));
      const other = join(otherDir, 'other.png');
      await makePng(other, 32);
      const otherSha = await hashFile(other);
      // The author lock must NOT be held during inference — otherwise this import
      // would deadlock/fail.
      await importAsset(root, {
        assetId: 'out',
        sourcePath: other,
        type: 'image',
        rights: RIGHTS,
        expectedRevision: before.revision,
      });
      fixture.release();
      await assert.rejects(() => pending, /different content/i);
      await rm(otherDir, { recursive: true, force: true });

      // No second POST; the per-attempt lock was released.
      assert.equal(fixture.requests.length, 1, 'a failed registration must not resubmit');
      assert.equal(existsSync(join(root, LOCK('req', 1))), false, 'the per-attempt lock was released');

      // The succeeded original + record are retained for safe recovery.
      assert.ok(existsSync(join(root, ORIGINAL('req', 1))), 'the provider original is retained');
      assert.equal(await hashFile(join(root, ORIGINAL('req', 1))), expectedSha);
      const job = JSON.parse(await readFile(join(root, JOB('req', 1)), 'utf8')) as {
        state: string;
        outputSha256: string;
      };
      assert.equal(job.state, 'succeeded');
      assert.equal(job.outputSha256, expectedSha);

      // The concurrent occupation (author state) is preserved and untouched.
      const after = await loadProject(root);
      assert.ok(after.revision > before.revision, 'the concurrent author edit is preserved');
      const occupied = after.assets.find(asset => asset.id === 'out')!;
      assert.equal(occupied.sha256, otherSha);
      assert.equal(await hashFile(join(root, occupied.path)), otherSha);

      // Recovery follows the SAME succeeded request against a free target id: no
      // new inference because of the local registration target.
      const recovered = await generateImage(root, { ...request(), asset: 'out2' }, testOnly(fixture.baseUrl));
      assert.equal(fixture.requests.length, 1, 'recovery must not trigger a second POST');
      assert.equal(recovered.asset.id, 'out2');
      assert.equal(recovered.asset.sha256, expectedSha);

      // The occupied Asset and the recovered Asset both remain, individually valid.
      const final = await loadProject(root);
      assert.equal(final.assets.find(asset => asset.id === 'out')!.sha256, otherSha);
      assert.equal(await hashFile(join(root, final.assets.find(asset => asset.id === 'out2')!.path)), expectedSha);
    });
  });
});

/**
 * An image-only Project carries NO timeline (`composition` absent), so the image
 * operation must never read movie output settings (width/height/fps/audio) from
 * one. Preflight and execution share the same judgement: both report/submit on
 * the same frozen request, and the real POST happens with no timeline fabricated.
 */
test('an image-only Project (no timeline) accepts preflight AND execution for generate and edit', async () => {
  await withRoot(async root => {
    // A legal image-only Project: a still target (never a composition).
    await writeFile(join(root, 'poster.html'), '<!doctype html><html><body>still</body></html>');
    const imageOnly = {
      schemaVersion: 1 as const,
      id: 'image-only',
      revision: 1,
      title: 'Image only',
      direction: {
        intent: 'a lone still',
        looks: [{ id: 'default', description: 'Default look' }],
        transitions: [],
      },
      assets: [],
      bindings: {},
      sources: [],
      imageDocuments: [{ id: 'poster', path: 'poster.html', resources: [], revision: 1 }],
      imageTargets: [
        {
          id: 'wide',
          document: 'poster',
          width: 320,
          height: 180,
          scale: 1,
          format: 'png' as const,
          background: 'opaque' as const,
        },
      ],
    };
    await writeFile(join(root, 'project.json'), `${JSON.stringify(validateProject(imageOnly), null, 2)}\n`);
    assert.equal((await loadProject(root)).composition, undefined, 'the Project carries no timeline');

    // A real reference Asset for the edit operation.
    await makePng(join(root, 'seed.png'), 32);
    await importAsset(root, {
      assetId: 'ref',
      sourcePath: join(root, 'seed.png'),
      type: 'image',
      rights: RIGHTS,
      expectedRevision: 1,
    });

    await withFixture(async fixture => {
      const options = testOnly(fixture.baseUrl);

      // --- generate: preflight says submit, execution really POSTs. ---
      const generateRequest = request({ id: 'generate-req', asset: 'still-gen' });
      const generateCheck = await preflightGenerateImage(root, generateRequest, options);
      assert.equal(generateCheck.ok, true, JSON.stringify(generateCheck.issues));
      assert.equal(generateCheck.action, 'submit');

      const generated = await generateImage(root, generateRequest, options);
      assert.equal(fixture.requests.length, 1, 'the execution performs the preflighted submit');
      assert.equal(fixture.requests[0]!.path, '/v1/images/generations');
      assert.equal(generated.asset.id, 'still-gen');
      assert.equal(generated.asset.type, 'image');
      assert.equal((await loadProject(root)).composition, undefined, 'no timeline is fabricated');

      // The persisted record carries the real request pixels, not movie output.
      const job = JSON.parse(await readFile(join(root, JOB('generate-req', 1)), 'utf8')) as Record<string, unknown>;
      assert.equal(job.size, undefined, 'a request without a size records none');
      assert.equal('output' in job, false, 'an image job carries no movie OutputSettings');

      // --- edit: same judgement, routed to the edits endpoint. ---
      const editRequest = request({
        id: 'edit-req',
        asset: 'still-edit',
        operation: 'edit',
        references: [{ asset: 'ref', category: 'image', role: 'identity' }],
        size: '512x512',
      });
      const editCheck = await preflightGenerateImage(root, editRequest, options);
      assert.equal(editCheck.ok, true, JSON.stringify(editCheck.issues));
      assert.equal(editCheck.action, 'submit');

      const edited = await generateImage(root, editRequest, options);
      assert.equal(fixture.requests.length, 2, 'the edit execution performs its own preflighted submit');
      assert.equal(fixture.requests[1]!.path, '/v1/images/edits');
      assert.equal(edited.asset.id, 'still-edit');
      assert.equal(edited.asset.imageGeneration?.operation, 'edit');
      assert.equal(edited.asset.imageGeneration?.size, '512x512');

      const editJob = JSON.parse(await readFile(join(root, JOB('edit-req', 1)), 'utf8')) as Record<string, unknown>;
      assert.equal(editJob.size, '512x512', 'the record keeps the actual requested pixels');
      assert.equal('output' in editJob, false, 'an image job carries no movie OutputSettings');
      assert.equal((await loadProject(root)).composition, undefined, 'the edit does not fabricate a timeline');
    });
  });
});
