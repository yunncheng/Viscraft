test('concurrent direct image API calls preflight without side effects, refuse the active lock, then reuse its record', async () => {
  await withRoot(async root => {
    await withDrivenFixture(async fixture => {
      const input = request({ id: 'concurrent-api' });
      const options = { testOnly: { baseUrl: fixture.baseUrl } };
      const first = generateImageApi(root, input, '.viscraft/scratch/concurrent/first.png', options);
      await fixture.waitForPost();
      await assert.rejects(
        generateImageApi(root, input, '.viscraft/scratch/concurrent/second.png', options),
        /already being generated/i,
        'a second caller that preflighted before the first job existed cannot pass the active lock',
      );
      assert.equal(fixture.requests.length, 1, 'the active lock prevents a duplicate POST');
      fixture.release();
      const firstResult = await first;
      const secondResult = await generateImageApi(root, input, '.viscraft/scratch/concurrent/second.png', options);
      assert.equal(fixture.requests.length, 1, 'the retry reloads and reuses the record committed by the first caller');
      const job = JSON.parse(await readFile(join(root, JOB('concurrent-api', 1)), 'utf8')) as {
        submitted: number;
        requestHash: string;
      };
      assert.equal(job.submitted, 1);
      assert.equal(firstResult.generation.requestHash, job.requestHash);
      assert.equal(secondResult.generation.requestHash, job.requestHash);
      assert.equal(
        await hashFile(join(root, '.viscraft/scratch/concurrent/first.png')),
        await hashFile(join(root, '.viscraft/scratch/concurrent/second.png')),
      );
      assert.equal(existsSync(join(root, LOCK('concurrent-api', 1))), false, 'the lock is released');
    });
  });
});

test('a retained successful image restores without its original reference bytes and rejects a changed operation', async () => {
  await withRoot(async root => {
    await withFixture(async fixture => {
      await makePng(join(root, 'reference.png'), 40);
      const referenceBytes = await readFile(join(root, 'reference.png'));
      const reference = {
        id: 'reference-image',
        revision: 1,
        path: 'reference.png',
        sha256: sha256(referenceBytes),
        type: 'image' as const,
        rights: RIGHTS,
        simulated: false,
      };
      const source = request({
        id: 'retained-edit',
        operation: 'edit',
        references: [{ asset: reference.id, category: 'image', role: 'identity' }],
      });
      const options = { testOnly: { baseUrl: fixture.baseUrl }, references: [{ asset: reference, root }] };
      await generateImageApi(root, source, '.viscraft/scratch/retained/1/image', options);
      assert.equal(fixture.requests.length, 1);
      const revisedDescriptor = { ...reference, revision: 2 };
      const changedProvenance = await preflightImageRequest(root, source, {
        ...options,
        references: [{ asset: revisedDescriptor, root }],
      });
      assert.equal(changedProvenance.requestUnchanged, false, 'reference revision is persisted provenance');
      await assert.rejects(
        generateImageApi(root, source, '.viscraft/scratch/retained/1/revision-changed', {
          ...options,
          references: [{ asset: revisedDescriptor, root }],
        }),
        /reference (?:provenance|ID, revision)|different current request/i,
      );
      assert.equal(fixture.requests.length, 1, 'changed reference provenance must not resubmit');
      await writeFile(join(root, 'reference.png'), Buffer.from('changed but still present'));
      await assert.rejects(
        generateImageApi(root, source, '.viscraft/scratch/retained/1/changed-bytes', options),
        /bytes do not match its recorded sha256/i,
      );
      assert.equal(fixture.requests.length, 1, 'present bytes with a mismatched declared hash cannot restore locally');
      await writeFile(join(root, 'reference.png'), referenceBytes);
      await rm(join(root, 'reference.png'));
      const preflight = await preflightImageRequest(root, source, options);
      assert.equal(preflight.requestUnchanged, true, 'completed image identity can be proven from current metadata');
      const retainedRecord = JSON.parse(await readFile(join(root, JOB('retained-edit', 1)), 'utf8')) as {
        requestHash: string;
      };
      assert.equal(preflight.requestHash, retainedRecord.requestHash);
      await assert.rejects(
        generateImageApi(root, { ...source, operation: 'generate' }, '.viscraft/scratch/retained/1/changed', options),
        /different current request/i,
      );
      assert.equal(fixture.requests.length, 1, 'operation mismatch must not submit or affect the retained record');
      const restored = await generateImageApi(root, source, '.viscraft/scratch/retained/1/restored', options);
      assert.equal(fixture.requests.length, 1, 'retained restore does not re-POST');
      assert.equal(restored.generation.operation, 'edit');
      assert.equal(
        await hashFile(join(root, '.viscraft/scratch/retained/1/restored')),
        restored.generation.outputSha256,
      );
    });
  });
});

test('a changed request is refused by BOTH the preflight and the execution with no extra POST', async () => {
  await withRoot(async root => {
    await createProject(root, { title: 'Changed' });
    await withFixture(async fixture => {
      await generateImage(root, request(), testOnly(fixture.baseUrl));
      const changed = { ...request(), prompt: 'a different scene entirely' };

      const check = await preflightGenerateImage(root, changed, testOnly(fixture.baseUrl));
      assert.equal(check.ok, false);
      assert.equal(check.action, 'blocked');
      assert.ok(
        check.issues.some(issue => issue.code === 'request-changed'),
        'a changed request is blocked with the specific request-changed reason',
      );
      // The same-content message must not mask the mismatch: the target IS
      // occupied by the matching success record, yet the action is blocked.
      assert.equal(check.target.exists, true);
      assert.notEqual(check.action, 'return-existing');
      assert.notEqual(check.action, 'resume-registration');

      await assert.rejects(
        () => generateImage(root, changed, testOnly(fixture.baseUrl)),
        /different frozen request|new attempt/i,
      );
      assert.equal(fixture.requests.length, 1, 'a changed request must not reuse the paid attempt');
    });
  });
});

test('an occupied target id with NO matching success record is blocked before submission (POST=0)', async () => {
  await withRoot(async root => {
    await createProject(root, { title: 'Occupied' });
    // Pre-register an Asset under the target id with genuinely different bytes.
    const otherDir = await mkdtemp(join(tmpdir(), 'viscraft-generate-image-other-'));
    const other = join(otherDir, 'other.png');
    await makePng(other, 32);
    const otherSha = await hashFile(other);
    const project = await loadProject(root);
    await importAsset(root, {
      assetId: 'out',
      sourcePath: other,
      type: 'image',
      rights: RIGHTS,
      expectedRevision: project.revision,
    });
    await withFixture(async fixture => {
      // --check refuses read-only, without guessing at the bytes.
      const check = await preflightGenerateImage(root, request(), testOnly(fixture.baseUrl));
      assert.equal(check.ok, false);
      assert.equal(check.action, 'blocked');
      assert.ok(
        check.issues.some(issue => issue.code === 'target-occupied'),
        `expected target-occupied, got ${JSON.stringify(check.issues)}`,
      );

      // Direct execution refuses before the adapter is ever called.
      await assert.rejects(() => generateImage(root, request(), testOnly(fixture.baseUrl)), /target-occupied/i);
      assert.equal(fixture.requests.length, 0, 'an occupied target must produce ZERO POSTs');
      assert.equal(existsSync(join(root, JOB('req', 1))), false, 'no job record was written');

      // The pre-existing Asset and its file are untouched.
      const after = await loadProject(root);
      const existing = after.assets.find(asset => asset.id === 'out')!;
      assert.equal(existing.sha256, otherSha);
      assert.equal(await hashFile(join(root, existing.path)), otherSha);
    });
    await rm(otherDir, { recursive: true, force: true });
  });
});

