import { fileURLToPath } from 'node:url';
/**
 * Status + capability diagnostics — status covers ALL routes truthfully
 * and doctor separates protocol capabilities, supported models and configuration.
 *
 *  - `status` must include successful image-api (`vllm-omni-image`) jobs, not only the
 *    simulated / runway / video-api / fal lanes, and must stay a pure read whose
 *    output carries no prompt text, no image bytes, no credentials and no URLs.
 *  - `doctor` reports all packaged models and their own parameter schemas.
 *    It describes available capabilities without selecting a model for a work.
 *  - `doctor` must not claim account availability: provider readiness is
 *    configuration only (no network query, no paid probe, no secret value).
 *
 * It drives the real CLI as a subprocess (the shipped `bin` entry) plus the SDK
 * status reader, against a real loopback HTTP fixture — no network egress.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
