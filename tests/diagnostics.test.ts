import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';
import type { AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  createProject,
  generateImageApi,
  runwayGen45Extension,
  gen4TurboExtension,
  type GenerateImageRequest,
} from '../src/index.js';
import { imageApiStatus } from '../src/backends/providers/services/vllm-omni/image-api.js';

const CLI = fileURLToPath(new URL('../src/cli.js', import.meta.url));

// A real, valid 1x1 PNG (signature-checked by the adapter); the image payload is
// never written into a job record, so its presence in status output would leak.
const PNG_BASE64 = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAAC0lEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==';
const PROMPT = 'a calm lighthouse at dusk over basalt cliffs';

function imageSource(attempt: number): GenerateImageRequest {
  return {
    id: `s_img_${attempt}`,
    attempt,
    asset: `out_img_${attempt}`,
    rights: { origin: 'generated by the vllm-omni-image fixture', license: 'CC0-1.0', redistributable: true },
    endpoint: 'test',
    operation: 'generate',
    model: 'Qwen-Image',
    prompt: PROMPT,
    references: [],
  };
}

/** Run the real CLI and resolve with stdout even when it exits non-zero (doctor
 * sets a non-zero exit when a host tool like a browser is absent). */
function runCli(
  args: string[],
  env: NodeJS.ProcessEnv = process.env,
): Promise<{ code: number; stdout: string; stderr: string }> {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [CLI, ...args], { stdio: ['ignore', 'pipe', 'pipe'], env });
    let stdout = '',
      stderr = '';
    child.stdout.on('data', (chunk: Buffer) => {
      stdout += String(chunk);
    });
    child.stderr.on('data', (chunk: Buffer) => {
      stderr += String(chunk);
    });
    child.on('error', reject);
    child.on('close', code => resolve({ code: code ?? 0, stdout, stderr }));
  });
}

/** A synchronous vllm-omni-image fixture returning genuine inline-base64 PNG bytes. */
async function withFixture(fn: (baseUrl: string) => Promise<void>): Promise<void> {
  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    const path = new URL(req.url ?? '/', 'http://127.0.0.1').pathname;
    req.resume();
    if (!(req.method === 'POST' && path === '/v1/images/generations')) {
      res.writeHead(404, { 'content-type': 'text/plain' });
      res.end('not found');
      return;
    }
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ created: 1, data: [{ b64_json: PNG_BASE64 }] }));
  });
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => resolve());
  });
  const baseUrl = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  try {
    await fn(baseUrl);
  } finally {
    await new Promise<void>((resolve, reject) => server.close(error => (error ? reject(error) : resolve())));
  }
}

test('status includes a successful image-api job (SDK + CLI) with no secrets', async () => {
  const root = await mkdtemp(join(tmpdir(), 'viscraft-diag-image-'));
  try {
    await createProject(root, { title: 'Diagnostics Image Fixture' });
    await withFixture(async baseUrl => {
      const source = imageSource(1);
      await generateImageApi(root, source, 'build/out.png', { testOnly: { baseUrl } });

      // SDK read: exactly one job, correct source/attempt.
      const sdkJobs = (await imageApiStatus(root)) as Record<string, unknown>[];
      assert.equal(sdkJobs.length, 1, 'imageApiStatus must report the one succeeded job');
      assert.equal(sdkJobs[0].sourceId, source.id);
      assert.equal(sdkJobs[0].attempt, source.attempt);
      assert.equal(sdkJobs[0].provider, 'vllm-omni-image');

      // CLI read: the succeeded job is reflected in the grouped providerJobs.
      const { code, stdout, stderr } = await runCli(['status', root]);
      assert.equal(code, 0, `status must exit 0 (stderr: ${stderr})`);
      const parsed = JSON.parse(stdout) as { providerJobs: { succeeded: number; pending: number } };
      assert.equal(parsed.providerJobs.succeeded, 1, 'status must count the one succeeded image-api job');
      assert.equal(parsed.providerJobs.pending, 0);

      // No secrets / prompt text / image bytes in the status output.
      assert.doesNotMatch(stdout, /calm lighthouse/, 'the prompt must never appear in status');
      assert.equal(stdout.includes(PNG_BASE64.slice(0, 32)), false, 'image bytes must never appear in status');
      assert.doesNotMatch(
        stdout,
        /bearer|authorization|api[_-]?key|secret|password/i,
        'no credential surface in status',
      );
    });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('doctor lists the complete packaged-model set and keeps models distinct', async () => {
  const { code, stdout, stderr } = await runCli(['doctor']);
  // doctor may exit non-zero when an optional host tool is absent; stdout is JSON.
  const parsed = JSON.parse(stdout) as {
    realVideoProvider: {
      packagedModels: { model: string; medium: string; protocol: string }[];
      protocolCapabilities: Record<string, { capabilityScope?: string; model?: unknown }>;
      modelCapabilities: Record<
        string,
        { model: string; medium: string; services: Record<string, { parameters: Record<string, any> }> }
      >;
    };
  };
  void code;
  void stderr;
  const video = parsed.realVideoProvider;
  const models = video.packagedModels.map(entry => entry.model);
  for (const expected of ['gen4.5', 'gen4_turbo', 'alibaba/wan-3.0/image-to-video', 'Seedance-2.5', 'MiniMax-H3']) {
    assert.ok(models.includes(expected), `packaged-model list must include '${expected}' (got ${models.join(', ')})`);
  }

  // gen4.5 and gen4_turbo are DISTINCT entries sharing the runway-v1 protocol,
  // and neither entry carries a protocol-level limit field (so gen4.5's 2..10s
  // duration is not silently applied to gen4_turbo).
  const gen45 = video.packagedModels.find(entry => entry.model === 'gen4.5');
  const turbo = video.packagedModels.find(entry => entry.model === 'gen4_turbo');
  assert.ok(gen45 && turbo, 'both Runway models must be present');
  assert.notEqual(gen45, turbo);
  for (const entry of [gen45, turbo]) {
    assert.equal(entry.protocol, 'runway-v1');
    assert.equal(entry.medium, 'video');
    assert.equal('durationSeconds' in entry, false, 'a per-model entry must not restate a protocol-level limit');
  }

  const runway = video.packagedModels.filter(entry => entry.protocol === 'runway-v1').map(entry => entry.model);
  assert.deepEqual(runway.sort(), ['gen4.5', 'gen4_turbo']);

  // The two extensions genuinely have DIFFERENT parameter ranges (proving that
  // treating them as one model would be wrong): gen4.5 REQUIRES a 2..10s
  // duration, gen4_turbo accepts an absent/any duration.
  assert.equal(runwayGen45Extension().model.id, 'gen4.5');
  assert.equal(gen4TurboExtension().model.id, 'gen4_turbo');
  assert.throws(() => runwayGen45Extension().model.parameters.parse({ ratio: '1280:720' }), /durationSeconds/i);
  assert.doesNotThrow(() => gen4TurboExtension().model.parameters.parse({ ratio: '1280:720' }));

  // The capability constants are marked TRANSPORT-level and carry NO default
  // model identity or per-model limit (those belong to the model definition).
  assert.equal(video.protocolCapabilities['runway-v1']?.capabilityScope, 'protocol');
  assert.equal(video.protocolCapabilities['fal-queue']?.capabilityScope, 'protocol');
  assert.equal(
    'model' in video.protocolCapabilities['runway-v1'],
    false,
    'transport capabilities must not name a default model',
  );
  assert.equal(
    'model' in video.protocolCapabilities['fal-queue'],
    false,
    'transport capabilities must not name a default model',
  );
  for (const protocol of ['runway-v1', 'fal-queue']) {
    for (const modelOwned of ['durationSeconds', 'ratios', 'resolutions', 'seed', 'outputFormats', 'proresProfiles']) {
      assert.equal(
        modelOwned in video.protocolCapabilities[protocol],
        false,
        `transport capabilities must not restate the model limit '${modelOwned}'`,
      );
    }
  }

  // Per-model limits are SOURCED FROM the model definition: the same field is
  // reported differently for two distinct Runway models because each model's own
  // zod schema differs (gen4.5 REQUIRES a 2..10s duration; gen4_turbo's is an
  // unbounded optional number), proving the limits are not a protocol default.
  for (const model of models) {
    assert.ok(video.modelCapabilities[model], `modelCapabilities must describe '${model}'`);
    assert.equal(video.modelCapabilities[model].model, model);
  }
  const cap45 = video.modelCapabilities['gen4.5'].services['runway-v1'];
  const capTurbo = video.modelCapabilities['gen4_turbo'].services['runway-v1'];
  assert.deepEqual(
    {
      min: cap45.parameters.durationSeconds.min,
      max: cap45.parameters.durationSeconds.max,
      integer: cap45.parameters.durationSeconds.integer,
    },
    { min: 2, max: 10, integer: true },
    'gen4.5 duration limits must come from its model definition',
  );
  assert.equal(
    capTurbo.parameters.durationSeconds.optional,
    true,
    'gen4_turbo duration is an optional, unbounded number in its own definition',
  );
  assert.equal(
    'min' in capTurbo.parameters.durationSeconds,
    false,
    "gen4_turbo must not inherit gen4.5's 2..10s range",
  );
  assert.equal(
    'max' in capTurbo.parameters.durationSeconds,
    false,
    "gen4_turbo must not inherit gen4.5's 2..10s range",
  );
  assert.deepEqual(cap45.parameters.ratio.values, [
    '1280:720',
    '720:1280',
    '1104:832',
    '960:960',
    '832:1104',
    '1584:672',
  ]);
  const capWan = video.modelCapabilities['alibaba/wan-3.0/image-to-video'].services['fal-queue'];
  assert.deepEqual(Object.keys(video.modelCapabilities['MiniMax-H3'].services).sort(), ['minimax-video-v2']);
  assert.deepEqual(video.modelCapabilities['minimax-h3-base-ref2va'].services['vllm-omni-video'].parameters, {});
  assert.deepEqual(video.modelCapabilities['MiniMax-H3'].services['minimax-video-v2'].parameters.resolution.values, [
    '768P',
    '2K',
  ]);
  assert.deepEqual(capWan.parameters.resolution.values, ['480p', '720p', '1080p']);
  assert.deepEqual(
    { min: capWan.parameters.durationSeconds.min, max: capWan.parameters.durationSeconds.max },
    { min: 2, max: 30 },
  );
});

test('doctor does not claim account availability', async () => {
  const home = await mkdtemp(join(tmpdir(), 'viscraft-doctor-config-'));
  try {
    await writeFile(
      join(home, 'endpoints.json'),
      JSON.stringify({
        video: [{ endpoint: 'default', service: 'runway', model: 'gen4.5', url: 'https://api.example.test' }],
      }),
    );
    const env = { ...process.env, VISCRAFT_CONFIG_HOME: home, VISCRAFT_VIDEO_API_KEY: 'sk-doctor-SECRET-value' };
    const { stdout } = await runCli(['doctor'], env);
    assert.ok(!stdout.includes('sk-doctor-SECRET-value'), 'doctor never prints a credential value');
    const parsed = JSON.parse(stdout) as {
      realVideoProvider: { serviceVerified: boolean; submissionAuthorized: boolean; realGenerationVerified: boolean };
      providers: {
        scope: string;
        capabilities: Record<string, { ready: boolean; endpoints: { credential: string; credentialSource: string }[] }>;
      };
    };
    const video = parsed.realVideoProvider;
    assert.equal(video.serviceVerified, false);
    assert.equal(video.submissionAuthorized, false);
    assert.equal(video.realGenerationVerified, false);
    const readiness = parsed.providers;
    assert.equal(readiness.capabilities['provider']!.ready, true);
    assert.deepEqual(
      readiness.capabilities['provider']!.endpoints.map(e => [e.credential, e.credentialSource]),
      [['VISCRAFT_VIDEO_API_KEY', 'environment']],
      'the vendor default credential name is reported with its source, not its value',
    );
    assert.equal(readiness.capabilities['image-generation']!.ready, false);
  } finally {
    await rm(home, { recursive: true, force: true });
  }
});
